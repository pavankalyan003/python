score = 50
print("Initial score (= 50):", score)
score += 10  # 50 + 10 = 60
print("After += 10:", score)
score -= 5  # 60 - 5 = 55
print("After -= 5:", score)
score *= 2  # 55 * 2 = 110
print("After *= 2:", score)
score /= 4  # 110 / 4 = 27.5
print("After /= 4:", score)
score //= 2  # 27.5 // 2 = 13.0
print("After //= 2:", score)
score %= 5  # 13.0 % 5 = 3.0
print("After %= 5:", score)
score **= 3  # 3.0 ** 3 = 27.0
print("After **= 3:", score)
