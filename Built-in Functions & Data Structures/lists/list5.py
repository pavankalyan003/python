# Write a program that accepts a list of numbers and prints every element along with its index using enumerate()

numbers = [10, 20, 30, 40, 50]

for index, value in enumerate(numbers):
    print("Index:", index, "Element:", value)


#output:
#Index: 0 Element: 10
#Index: 1 Element: 20
#Index: 2 Element: 30
#Index: 3 Element: 40
#Index: 4 Element: 50
    
    
